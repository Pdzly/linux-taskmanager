"""Subset the Lucide icon font to the icons in tools/icons.txt.

Usage: python3 tools/build_icons.py <lucide.ttf> <info.json> [fonttools-dir]

Get lucide.ttf and info.json from the lucide-static npm package (font/ folder).
Writes crates/app/fonts/lucide-subset.ttf and crates/app/ui/icons.slint.
Icons are a font rather than SVG files because Slint's software renderer
re-rasterizes SVGs on every draw, while glyphs are cached.
"""
import json
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
font_path, info_path = sys.argv[1], sys.argv[2]
if len(sys.argv) > 3:
    sys.path.insert(0, sys.argv[3])
from fontTools import subset  # noqa: E402
from fontTools.ttLib import TTFont  # noqa: E402

info = json.loads(Path(info_path).read_text())
icons = []
for line in (root / "tools/icons.txt").read_text().splitlines():
    line = line.split("#")[0].strip()
    if line:
        name, lucide = line.split()
        icons.append((name, int(info[lucide]["encodedCode"].lstrip("\\"), 16)))

opts = subset.Options()
opts.layout_features = []
opts.name_IDs = ["*"]
opts.notdef_outline = True
font = TTFont(font_path)
sub = subset.Subsetter(opts)
sub.populate(unicodes=[cp for _, cp in icons])
sub.subset(font)

# Lucide outlines are centered in their 1000-unit advance width, but their
# hmtx side bearings are zero. Slint centers the advance box, so retain each
# nonempty glyph's actual left extent as its LSB to center the rendered ink.
glyf = font["glyf"]
hmtx = font["hmtx"]
for glyph_name in font.getGlyphOrder():
    glyph = glyf[glyph_name]
    if glyph.numberOfContours == 0 and not glyph.isComposite():
        continue
    advance_width, _ = hmtx[glyph_name]
    hmtx[glyph_name] = advance_width, glyph.xMin

out_font = root / "crates/app/fonts/lucide-subset.ttf"
font.save(out_font)
family = font["name"].getDebugName(1)

lines = [
    "// Generated by tools/build_icons.py from tools/icons.txt. Do not edit.",
    "// Lucide icons (ISC licence, see fonts/LUCIDE-LICENSE).",
    "",
    "export global Icons {",
    f'    out property <string> font: "{family}";',
]
lines += [f'    out property <string> {name}: "\\u{{{cp:x}}}";' for name, cp in icons]
lines.append("}")
(root / "crates/app/ui/icons.slint").write_text("\n".join(lines) + "\n")
print(f"{len(icons)} icons, family {family!r}, {out_font.stat().st_size} bytes")
